const scheduleByDate = new Map(bibleSchedule.map((r) => [r.date, r]));

function toIsoDate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

const REST_DAY: BibleReading = {
  id: 0,
  date: "",
  reference: "오늘은 쉬는 날 🌿",
  book: "주일",
  chapters: "쉼",
};

// Get reading by specific date (returns rest entry if no reading scheduled)
export function getReadingByDate(date: Date): BibleReading {
  const iso = toIsoDate(date);
  const r = scheduleByDate.get(iso);
  if (r) return r;
  return { ...REST_DAY, date: iso };
}

// Today's reading. If today has no entry (Sunday or out of plan range),
// fall back to the next upcoming reading so the user always sees something.
export function getTodayReading(): BibleReading {
  const today = new Date();
  const iso = toIsoDate(today);
  const r = scheduleByDate.get(iso);
  if (r) return r;

  // find next scheduled reading within 7 days
  for (let i = 1; i <= 7; i++) {
    const d = new Date(today);
    d.setDate(d.getDate() + i);
    const next = scheduleByDate.get(toIsoDate(d));
    if (next) return next;
  }
  // out of range — return last reading
  return bibleSchedule[bibleSchedule.length - 1];
}

// Readings for a calendar month
export function getMonthReadings(year: number, month: number): BibleReading[] {
  const readings: BibleReading[] = [];
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  for (let day = 1; day <= daysInMonth; day++) {
    readings.push(getReadingByDate(new Date(year, month, day)));
  }
  return readings;
}

// Day index within the reading plan (1-based). Returns 0 if today not in plan.
export function getDayOfYear(date: Date = new Date()): number {
  const r = scheduleByDate.get(toIsoDate(date));
  return r ? r.id : 0;
}
