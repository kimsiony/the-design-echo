// Get today's reading based on day of year
export function getTodayReading(): BibleReading {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Ensure we stay within bounds (1-365)
  const index = Math.max(0, Math.min(dayOfYear - 1, 364));
  return bibleSchedule[index];
}

// Get reading by specific date
export function getReadingByDate(date: Date): BibleReading {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  const index = Math.max(0, Math.min(dayOfYear - 1, 364));
  return bibleSchedule[index];
}

// Get readings for a month (for calendar view)
export function getMonthReadings(year: number, month: number): BibleReading[] {
  const readings: BibleReading[] = [];
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  
  for (let day = 1; day <= daysInMonth; day++) {
    const date = new Date(year, month, day);
    readings.push(getReadingByDate(date));
  }
  
  return readings;
}

// Get day of year (1-365)
export function getDayOfYear(date: Date = new Date()): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}
